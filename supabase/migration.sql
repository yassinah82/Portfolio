-- --------------------------------------------------------------------
-- 1. TABLE: messages
-- Stores contact form submissions.
-- --------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    message TEXT NOT NULL,
    is_read BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_messages_created_at ON public.messages(created_at DESC);

-- Enable Row Level Security (RLS)
ALTER TABLE public.messages ENABLE ROW LEVEL SECURITY;

-- Drop existing policies if re-running
DROP POLICY IF EXISTS "Public can submit contact messages" ON public.messages;
DROP POLICY IF EXISTS "Service role full access on messages" ON public.messages;

-- RLS Policy 1: Public (anon and authenticated) can INSERT contact messages
CREATE POLICY "Public can submit contact messages"
ON public.messages
FOR INSERT
TO anon, authenticated
WITH CHECK (true);

-- RLS Policy 2: Service Role has full access (read, mark read, delete from backend)
CREATE POLICY "Service role full access on messages"
ON public.messages
FOR ALL
TO service_role
USING (true)
WITH CHECK (true);


-- --------------------------------------------------------------------
-- 2. TABLE: skills
-- Stores technical skill cards displayed on the portfolio.
-- --------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.skills (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    description TEXT NOT NULL,
    icon VARCHAR(100) NOT NULL DEFAULT 'fas fa-code',
    tags TEXT[] DEFAULT '{}',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_skills_created_at ON public.skills(created_at DESC);

-- Enable Row Level Security (RLS)
ALTER TABLE public.skills ENABLE ROW LEVEL SECURITY;

-- Drop existing policies if re-running
DROP POLICY IF EXISTS "Public can read skills" ON public.skills;
DROP POLICY IF EXISTS "Service role full access on skills" ON public.skills;

-- RLS Policy 1: Anyone can read skills publicly
CREATE POLICY "Public can read skills"
ON public.skills
FOR SELECT
TO anon, authenticated
USING (true);

-- RLS Policy 2: Service Role has full access (add, edit, delete skills from backend)
CREATE POLICY "Service role full access on skills"
ON public.skills
FOR ALL
TO service_role
USING (true)
WITH CHECK (true);


-- --------------------------------------------------------------------
-- 3. TABLE: projects
-- Stores project cards displayed on homepage and projects page.
-- --------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    description TEXT NOT NULL,
    image_url TEXT,
    tags TEXT[] DEFAULT '{}',
    live_url TEXT,
    details_url TEXT,
    is_featured BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_projects_created_at ON public.projects(created_at DESC);

-- Enable Row Level Security (RLS)
ALTER TABLE public.projects ENABLE ROW LEVEL SECURITY;

-- Drop existing policies if re-running
DROP POLICY IF EXISTS "Public can read projects" ON public.projects;
DROP POLICY IF EXISTS "Service role full access on projects" ON public.projects;

-- RLS Policy 1: Anyone can read projects publicly
CREATE POLICY "Public can read projects"
ON public.projects
FOR SELECT
TO anon, authenticated
USING (true);

-- RLS Policy 2: Service Role has full access (add, edit, delete projects from backend)
CREATE POLICY "Service role full access on projects"
ON public.projects
FOR ALL
TO service_role
USING (true)
WITH CHECK (true);


